export function computeDecisionScore(scores: DecisionEngineScores): number {
  const weighted =
    scores.skillAlignment * 0.3 +
    scores.xelimeRelevance * 0.25 +
    scores.incomePotential * 0.2 +
    scores.workFlexibility * 0.15 +
    scores.professionalDevelopment * 0.1;
  return Number(weighted.toFixed(1));
}

